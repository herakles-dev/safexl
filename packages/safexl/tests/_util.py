def fixture_path(name: str) -> Path:
    """Path of a real third-party workbook; skips the test if it is absent."""
    p = FIXTURES_DIR / name
    if not p.is_file():
        if name in OWN_FIXTURES:
            pytest.skip(f"{name} is expected in the repository at {p}; restore the file")
        pytest.skip(SKIP_REASON)
    return p


def corpus_path(name: str) -> Path:
    """Path of a benchmark-corpus workbook; skips the test if it is absent."""
    p = REPO_ROOT / "research" / "xlsx-bench" / "corpus" / name
    if not p.is_file():
        pytest.skip(SKIP_REASON)
    return p


def all_fixture_paths() -> list[Path]:
    return [fixture_path(n) for n in FIXTURE_NAMES]


