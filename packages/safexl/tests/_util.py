# Minimal synthetic two-sheet .xlsx builder -- for cross-sheet formula
# reference tests (insert_rows, rename_sheet) and add_sheet's "next available
# sheet number" test, where a single-sheet workbook can't exercise the
# behavior.
# ---------------------------------------------------------------------------

_WORKBOOK_XML_2SHEETS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="{sheet1_name}" sheetId="1" r:id="rId1"/><sheet name="{sheet2_name}" sheetId="2" r:id="rId2"/></sheets>
</workbook>"""

_WORKBOOK_RELS_2SHEETS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet2.xml"/>
</Relationships>"""

_CONTENT_TYPES_2SHEETS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
<Override PartName="/xl/worksheets/sheet2.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
</Types>"""


def _sheet_data_xml(cells: dict[str, str] | None) -> str:
    """Build a full <worksheet>...</worksheet> part (with a dimension
    computed to exactly bound ``cells``) -- the same logic build_minimal_workbook
    uses for its single sheet, factored out so build_two_sheet_workbook can
    build two independent sheets with it."""
    cells = cells if cells is not None else {}
    by_row: dict[int, list[tuple[int, str]]] = {}
    min_col = min_row = max_col = max_row = None
    for ref, c_xml in cells.items():
        letters, row = _split_ref(ref)
        col = _col_to_num(letters)
        min_col = col if min_col is None else min(min_col, col)
        max_col = col if max_col is None else max(max_col, col)
        min_row = row if min_row is None else min(min_row, row)
        max_row = row if max_row is None else max(max_row, row)
        by_row.setdefault(row, []).append((col, c_xml))

    rows_xml_parts = []
    for r in sorted(by_row):
        ordered_cells = [c for _col, c in sorted(by_row[r], key=lambda pair: pair[0])]
        rows_xml_parts.append(f'<row r="{r}">{"".join(ordered_cells)}</row>')
    rows_xml = "".join(rows_xml_parts)

    if min_col is None:
        dim = "A1"
    elif min_col == max_col and min_row == max_row:
        dim = f"{_num_to_col(min_col)}{min_row}"
    else:
        dim = f"{_num_to_col(min_col)}{min_row}:{_num_to_col(max_col)}{max_row}"

    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
        f'<dimension ref="{dim}"/><sheetData>{rows_xml}</sheetData></worksheet>'
    )


def build_two_sheet_workbook(
    dst: Path,
    sheet1_name: str = "Sheet1",
    sheet2_name: str = "Sheet2",
    sheet1_cells: dict[str, str] | None = None,
    sheet2_cells: dict[str, str] | None = None,
) -> Path:
    """Write a minimal, structurally-valid two-sheet .xlsx."""
    workbook_xml = _WORKBOOK_XML_2SHEETS.format(sheet1_name=sheet1_name, sheet2_name=sheet2_name)

    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", _CONTENT_TYPES_2SHEETS)
        z.writestr("_rels/.rels", _ROOT_RELS)
        z.writestr("xl/workbook.xml", workbook_xml)
        z.writestr("xl/_rels/workbook.xml.rels", _WORKBOOK_RELS_2SHEETS)
        z.writestr("xl/worksheets/sheet1.xml", _sheet_data_xml(sheet1_cells))
        z.writestr("xl/worksheets/sheet2.xml", _sheet_data_xml(sheet2_cells))
    return dst
