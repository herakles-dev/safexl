def sha256_of(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def zip_part_hashes(path) -> dict[str, str]:
    """{zip member name: sha256 hex digest}, directory entries excluded."""
    with zipfile.ZipFile(path) as z:
        return {n: sha256_of(z.read(n)) for n in z.namelist() if not n.endswith("/")}


def read_zip_text(path, name: str) -> str:
    """Read one zip member's contents as UTF-8 text (e.g. any worksheet part,
    not just sheet1.xml -- see sheet1_xml for the common single-sheet case)."""
    with zipfile.ZipFile(path) as z:
        return z.read(name).decode("utf-8")


def first_sheet_name(path) -> str:
    with zipfile.ZipFile(path) as z:
        wb = z.read("xl/workbook.xml").decode("utf-8", errors="replace")
    m = re.search(r'<sheet\b[^>]*\bname="([^"]+)"', wb)
    assert m, f"no <sheet name=...> found in xl/workbook.xml of {path}"
    return m.group(1)


_ROW_SIMPLE_RE = re.compile(r'<row\b[^>]*\br="(\d+)"')
_CELL_SIMPLE_RE = re.compile(r'<c\b[^>]*\br="([A-Za-z]+\d+)"')


def row_order(sheet_xml: str) -> list[int]:
    """<row r="N"> values in document order (as written, not sorted)."""
    return [int(m.group(1)) for m in _ROW_SIMPLE_RE.finditer(sheet_xml)]


def cell_refs_in_row(sheet_xml: str, row_num: int) -> list[str]:
    """<c r="..."> refs inside <row r="row_num"> in document order."""
    m = re.search(rf'<row\b[^>]*\br="{row_num}"[^>]*>(.*?)</row>', sheet_xml, re.DOTALL)
    if not m:
        return []
    return [cm.group(1) for cm in _CELL_SIMPLE_RE.finditer(m.group(0))]


def sheet1_xml(path) -> str:
    with zipfile.ZipFile(path) as z:
        return z.read("xl/worksheets/sheet1.xml").decode("utf-8")


# ---------------------------------------------------------------------------
# Minimal synthetic .xlsx builder -- a small, structurally-valid OOXML
# package built by hand (stdlib zipfile only, matching the engine's own
# dependency-free philosophy) so engine-behavior unit tests (value types,
# row/cell ordering, dimension math, calcPr branches) can assert exact,
# deterministic output without depending on a real fixture's incidental
# layout. Real fixtures are used separately for byte-identity / feature /
# whole-file coverage.
# ---------------------------------------------------------------------------

_CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
</Types>"""

_ROOT_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>"""

_WORKBOOK_XML = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="{sheet_name}" sheetId="1" r:id="rId1"/></sheets>
</workbook>"""

_WORKBOOK_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
</Relationships>"""

_CALC_CHAIN_XML = (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
    '<calcChain xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
    '<c r="B2" i="1"/></calcChain>'
)

_CALC_CHAIN_OVERRIDE = (
    '<Override PartName="/xl/calcChain.xml" '
    'ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.calcChain+xml"/>'
)


def _col_to_num(letters: str) -> int:
    n = 0
    for ch in letters:
        n = n * 26 + (ord(ch.upper()) - 64)
    return n


def _num_to_col(n: int) -> str:
    letters = ""
    while n > 0:
        n, rem = divmod(n - 1, 26)
        letters = chr(65 + rem) + letters
    return letters


def _split_ref(ref: str) -> tuple[str, int]:
    m = re.match(r"([A-Za-z]+)(\d+)", ref)
    assert m, f"not a cell ref: {ref!r}"
    return m.group(1), int(m.group(2))


def build_minimal_workbook(
    dst: Path,
    sheet_name: str = "Sheet1",
    cells: dict[str, str] | None = None,
    extra_workbook_xml: str = "",
    extra_content_types_xml: str = "",
    extra_sheet_xml: str = "",
    include_dimension: bool = True,
    include_calc_chain: bool = False,
) -> Path:
    """Write a minimal, structurally-valid .xlsx with one sheet.

    ``cells``: {ref: full "<c ...>...</c>" XML string}, e.g.
    ``{"A1": '<c r="A1"><v>1</v></c>'}``. Rows/cells are emitted in ascending
    ref order (so the seed file itself satisfies
    ``validate.check_row_cell_order``); dimension is computed to exactly
    bound the seeded cells (dropped entirely if ``include_dimension=False``).

    ``extra_workbook_xml`` is inserted just before ``</workbook>`` (e.g. a
    ``<calcPr .../>`` element). ``extra_content_types_xml`` is inserted just
    before ``</Types>``. ``extra_sheet_xml`` is inserted just after
    ``</sheetData>`` (e.g. a ``<mergeCells>...</mergeCells>`` block).
    ``include_calc_chain=True`` adds a (deliberately trivial)
    ``xl/calcChain.xml`` part plus its Content_Types Override, to exercise
    the engine's unconditional-drop behavior from a known starting state.
    """
    cells = cells if cells is not None else {"A1": '<c r="A1"><v>1</v></c>'}

    by_row: dict[int, list[tuple[int, str]]] = {}
    min_col = min_row = max_col = max_row = None
    for ref, c_xml in cells.items():
        letters, row = _split_ref(ref)
        col = _col_to_num(letters)
        min_col = col if min_col is None else min(min_col, col)
        max_col = col if max_col is None else max(max_col, col)
        min_row = row if min_row is None else min(min_row, row)
        max_row = row if max_row is None else max(max_row, row)
        by_row.setdefault(row, []).append((col, c_xml))

    if min_col is None:
        dim = "A1"
    elif min_col == max_col and min_row == max_row:
        dim = f"{_num_to_col(min_col)}{min_row}"
    else:
        dim = f"{_num_to_col(min_col)}{min_row}:{_num_to_col(max_col)}{max_row}"

    rows_xml_parts = []
    for r in sorted(by_row):
        ordered_cells = [c for _col, c in sorted(by_row[r], key=lambda pair: pair[0])]
        rows_xml_parts.append(f'<row r="{r}">{"".join(ordered_cells)}</row>')
    rows_xml = "".join(rows_xml_parts)

    dimension_xml = f'<dimension ref="{dim}"/>' if include_dimension else ""
    sheet_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
        f"{dimension_xml}<sheetData>{rows_xml}</sheetData>{extra_sheet_xml}</worksheet>"
    )

    content_types = _CONTENT_TYPES.replace("</Types>", extra_content_types_xml + "</Types>")
    if include_calc_chain:
        content_types = content_types.replace("</Types>", _CALC_CHAIN_OVERRIDE + "</Types>")

    workbook_xml = _WORKBOOK_XML.format(sheet_name=sheet_name)
    if extra_workbook_xml:
        workbook_xml = workbook_xml.replace("</workbook>", extra_workbook_xml + "</workbook>")

    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", content_types)
        z.writestr("_rels/.rels", _ROOT_RELS)
        z.writestr("xl/workbook.xml", workbook_xml)
        z.writestr("xl/_rels/workbook.xml.rels", _WORKBOOK_RELS)
        z.writestr("xl/worksheets/sheet1.xml", sheet_xml)
        if include_calc_chain:
            z.writestr("xl/calcChain.xml", _CALC_CHAIN_XML)
    return dst


