# corpus files (hand-verified counts)
# --------------------------------------------------------------------------

def test_simple_monthly_budget():
    r = inventory(corpus_path("simple-monthly-budget.xlsx"))
    assert r["sheet_names"] == ["Simple Monthly Budget"]
    assert r["vba"]["present"] is False
    assert r["charts"]["count"] == 1
    assert r["tables"]["count"] == 2
    assert r["conditional_formatting"]["classic"]["count"] == 1
    assert r["conditional_formatting"]["x14"]["count"] == 1
    assert len(r["defined_names"]) == 2
    assert r["images"]["count"] == 1
    assert r["merged_cells"]["count"] == 5
    # the chart's series must reference a range on the budget sheet, not a
    # dangling/empty ref — this is exactly what a row-insert can silently break
    chart = r["charts"]["charts"][0]
    assert chart["n_series"] >= 1
    assert any(s["val_ref"] for s in chart["series"])


