"""Pytest checks for research/xlsx-bench/inventory.py.

Every expected count below was hand-verified against the raw zip/XML content
(independently of inventory.py's own extraction code — via direct
`str.count()` on the relevant XML parts) before being written into this
file. See the sibling investigation notes in corpus.json's `why_hard` /
`inventory_summary` fields for the same numbers, generated by running the
tool itself.
"""
import importlib.util
import sys
from pathlib import Path

import pytest

from _corpus import require

HERE = Path(__file__).resolve().parent
BENCH_DIR = HERE.parent
CORPUS_DIR = BENCH_DIR / "corpus"
FIXTURES_DIR = BENCH_DIR.parent / "safexl-moat" / "fixtures"

# Import inventory.py by path so this test works regardless of how pytest
# is invoked (no package __init__.py required).
_spec = importlib.util.spec_from_file_location("xlsx_bench_inventory", BENCH_DIR / "inventory.py")
inventory_module = importlib.util.module_from_spec(_spec)
sys.modules["xlsx_bench_inventory"] = inventory_module
_spec.loader.exec_module(inventory_module)
inventory = inventory_module.inventory


def corpus_path(name: str) -> str:
    return str(require(CORPUS_DIR / name))


def fixture_path(name: str) -> str:
    return str(require(FIXTURES_DIR / name))


