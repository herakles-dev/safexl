# --------------------------------------------------------------------------
# stability / robustness of the tool itself
# --------------------------------------------------------------------------

@pytest.mark.parametrize(
    "name",
    [
        "simple-monthly-budget.xlsx",
        "benefits-contribution-calculator.xlsm",
        "structured-refs-lookup-tool.xlsx",
        "pivot-chart-report.xlsx",
        "pension-hedging-stress-model.xlsx",
        "sparkline-external-reference.xlsx",
        "kyc-intake-data-dictionary.xlsx",
        "parking-study-report.xlsm",
    ],
)
def test_inventory_runs_clean_on_every_corpus_file(name):
    r = inventory(corpus_path(name))
    assert r["file"] == corpus_path(name)
    assert r["size_bytes"] > 0
    assert len(r["sheet_names"]) > 0
    assert len(r["part_sha256"]) > 0
    # every declared sheet name resolved to at least a worksheet part somewhere
    # in the zip (i.e. sheet_map didn't silently drop entries)
    assert isinstance(r["part_sha256"], dict)


def test_inventory_is_deterministic():
    path = corpus_path("simple-monthly-budget.xlsx")
    r1 = inventory(path)
    r2 = inventory(path)
    assert r1 == r2
